"""Assemble the skill for its hosts (the product name comes from product.py).

One common body (``skill/``), one runtime (this package's v2 modules and the viewer) and
the v2 examples become self-contained folders:

    <out>/hermes/<name>/                 a Hermes skill directory
    <out>/claude-code/<name>/            a Claude Code plugin; its skills/<name>/ also works
                                         on its own as .claude/skills/<name>

Only the frontmatter and the skill-directory token differ between hosts. Every package
carries MANIFEST.json (version, contract, SHA-256 of each file). Usage:

    python3 construct_hologram/package.py --out /some/empty/folder [--host hermes|claude-code|all]
"""

import argparse
import hashlib
import importlib
import json
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
try:
    from . import product
except ImportError:  # run as a script
    sys.path.insert(0, str(REPO))
    product = importlib.import_module(HERE.name + ".product")
NAME = product.NAME
TITLE = product.TITLE
VERSION = product.VERSION
CONTRACT = product.CONTRACT
AUTHOR = product.AUTHORS
LICENSE = product.LICENSE
PACKAGE = HERE.name  # the Python package's folder, also its folder inside each skill's runtime/
COMPATIBILITY = ("Python 3.10+ (standard library only). Captures need a local Chromium-family "
                 "browser; video needs ffmpeg. Nothing is installed or downloaded.")
TAGS = ["Construct", "Hologram", "3D", "Visualization", "WebGL", "Animation", "Design"]

# The runtime: the v2 toolchain plus the v1 module its CLI still dispatches to.
RUNTIME_MODULES = ["__init__.py", "__main__.py", "product.py", "hologram.py", "scene.py", "shapes.py",
                   "audit.py", "diagnose.py", "params.py", "prompts.py", "render.py", "runner.py", "studio.py", "png.py",
                   "trace.py", "terrain.py", "tiers.py", "globe.py", "critic.py", "compare.py", "archkit.py", "rounds.py",
                   "film_audio.py"]
FILM = ["construct-three.js"]  # film mode's optional three.js loader, shipped as runtime/film/
VIEWER_FILES = ["hologram.js", "film.js", "template.html"]
PROMPT_EXAMPLES = ["case-jewel.params.json", "book.json"]

# How each host names the skill's own folder inside SKILL.md.
SKILL_DIR_TOKEN = {
    "hermes": "${HERMES_SKILL_DIR}",
    "claude-code": "${CLAUDE_SKILL_DIR}",
}

CLI_SHIM = '''"""{name} command line. Run by absolute path from any folder."""
import importlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
main = importlib.import_module("{package}.__main__").main

if __name__ == "__main__":
    sys.exit(main())
'''

NOTICE = """{name} {version}
Copyright 2026 {author}. Licensed under {license} (see LICENSE).

Independently authored. Its look and construction grew out of NODE's Measured Light holograms
(same author); its working method is inspired by Anatomy (github.com/wheresryan22/anatomy, MIT).
No NODE or Anatomy code, fonts, shaders, assets or text are included. No third-party code,
fonts, models or datasets are bundled: the runtime is Python standard library, the viewer is
plain WebGL2 using system fonts. Optional external programs it can call if already installed:
a Chromium-family browser (captures) and ffmpeg (video); each keeps its own licence and is
never downloaded or installed by this package.

The example artwork in examples/assets is synthetic, generated by png.py, and labelled as
generated decoration. No authentic artwork, private collection data, credentials or model
weights are included.
"""


class PackageError(Exception):
    pass


def split_frontmatter(text):
    if not text.startswith("---\n"):
        raise PackageError("SKILL.md has no frontmatter")
    end = text.index("\n---\n", 4)
    fields = {}
    for line in text[4:end].splitlines():
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip()
    return fields, text[end + 5:]


def _yaml_str(value):
    return json.dumps(value, ensure_ascii=False)


def frontmatter(host, fields):
    lines = ["---", "name: " + fields["name"], "description: " + _yaml_str(fields["description"])]
    if host == "claude-code":
        lines += ["license: " + LICENSE, "compatibility: " + _yaml_str(COMPATIBILITY)]
    if host == "hermes":
        lines += ["version: " + VERSION, "author: " + AUTHOR, "license: " + LICENSE,
                  "metadata:", "  hermes:",
                  "    tags: [" + ", ".join(TAGS) + "]",
                  "    related_skills: []"]
    lines.append("---")
    return "\n".join(lines) + "\n"


def render_skill_md(host):
    text = (HERE / "skill" / "SKILL.md").read_text(encoding="utf-8")
    fields, body = split_frontmatter(text.replace("{{NAME}}", NAME).replace("{{TITLE}}", TITLE))
    for key in ("name", "description"):
        if not fields.get(key):
            raise PackageError("SKILL.md frontmatter lacks " + key)
    if fields["name"] != NAME:
        raise PackageError("SKILL.md name must be " + NAME)
    if len(fields["description"]) > 1024:
        raise PackageError("description longer than 1024 characters")
    body = body.replace("{{SKILL_DIR}}", SKILL_DIR_TOKEN[host])
    if "{{" in body:
        raise PackageError("unreplaced placeholder in SKILL.md")
    return frontmatter(host, fields) + body


def _copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(src, dst)


def write_skill(host, root):
    """Write the skill folder (SKILL.md, references, runtime, examples) into root."""
    root.mkdir(parents=True, exist_ok=False)
    (root / "SKILL.md").write_text(render_skill_md(host), encoding="utf-8")
    for ref in sorted((HERE / "skill" / "references").glob("*.md")):
        _copy(ref, root / "references" / ref.name)
    for module in RUNTIME_MODULES:
        _copy(HERE / module, root / "runtime" / PACKAGE / module)
    for name in VIEWER_FILES:
        _copy(HERE / "viewer" / name, root / "runtime" / PACKAGE / "viewer" / name)
    for name in PROMPT_EXAMPLES:  # the prompts quote these: critique, author and prompts need them
        _copy(HERE / "examples" / "v2" / name, root / "runtime" / PACKAGE / "examples" / "v2" / name)
    for name in FILM:
        _copy(HERE / "film" / name, root / "runtime" / "film" / name)
    (root / "runtime" / "cli.py").write_text(CLI_SHIM.format(name=NAME, package=PACKAGE), encoding="utf-8")
    for scene in sorted((HERE / "examples" / "v2").glob("*.json")):
        _copy(scene, root / "examples" / scene.name)
    for asset in sorted((HERE / "examples" / "v2" / "assets").glob("*.png")):
        _copy(asset, root / "examples" / "assets" / asset.name)
    _copy(REPO / "CONTRACT.md", root / "CONTRACT.md")
    _copy(HERE / "geometry.schema.json", root / "geometry.schema.json")
    for f in sorted((HERE / "prompts").iterdir()):
        _copy(f, root / "prompts" / f.name)


def write_legal(root):
    _copy(REPO / "LICENSE", root / "LICENSE")
    (root / "NOTICE").write_text(NOTICE.format(name=NAME, version=VERSION, author=AUTHOR, license=LICENSE),
                                 encoding="utf-8")


def write_manifest(root, host):
    files = {}
    for path in sorted(p for p in root.rglob("*") if p.is_file()):
        rel = path.relative_to(root).as_posix()
        files[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
    manifest = {"name": NAME, "version": VERSION, "contract": CONTRACT, "host": host,
                "files": files}
    (root / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def build_hermes(out):
    root = out / "hermes" / NAME
    write_skill("hermes", root)
    write_legal(root)
    write_manifest(root, "hermes")
    return root


def build_claude_code(out):
    root = out / "claude-code" / NAME
    skill = root / "skills" / NAME
    write_skill("claude-code", skill)
    write_legal(skill)
    write_legal(root)
    plugin = {
        "name": NAME,
        "version": VERSION,
        "description": product.TAGLINE + " Audited, animated holographic constructs of objects, buildings, "
                       "machines and creatures, with visual review.",
        "author": {"name": AUTHOR},
        "license": LICENSE,
        "keywords": [t.lower() for t in TAGS],
    }
    (root / ".claude-plugin").mkdir(parents=True)
    (root / ".claude-plugin" / "plugin.json").write_text(json.dumps(plugin, indent=2) + "\n",
                                                         encoding="utf-8")
    # the opt-in budget hook and its recipe: shipped, never switched on by installing the plugin
    hooks = HERE.parent / "hosts" / "claude-code"
    for name in ("construct_budget.py", "README.md"):
        if (hooks / name).exists():
            _copy(hooks / name, root / "hosts" / name)
    write_manifest(root, "claude-code")
    return root


BUILDERS = {"hermes": build_hermes, "claude-code": build_claude_code}


def build(out, hosts=("hermes", "claude-code")):
    out = Path(out)
    if out.exists() and any(out.iterdir()):
        raise PackageError("output folder is not empty: %s" % out)
    out.mkdir(parents=True, exist_ok=True)
    return {host: BUILDERS[host](out) for host in hosts}


def main(argv=None):
    parser = argparse.ArgumentParser(prog="package", description=__doc__.splitlines()[0])
    parser.add_argument("--out", required=True, help="an empty or new folder")
    parser.add_argument("--host", choices=("all",) + tuple(BUILDERS), default="all")
    args = parser.parse_args(argv)
    hosts = tuple(BUILDERS) if args.host == "all" else (args.host,)
    try:
        roots = build(args.out, hosts)
    except (PackageError, OSError) as exc:
        sys.stderr.write("package: %s\n" % exc)
        return 1
    for host, root in roots.items():
        sys.stdout.write("%s: %s\n" % (host, os.path.abspath(root)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
